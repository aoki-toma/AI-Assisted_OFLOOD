#!/usr/bin/env bash
# File: compute_cv.sh
# Description: calculate collective variables using cpptraj
set -euo pipefail

_traj_file="${1}"
_top_file="${2}"
_structure_file="${3}"
_out_file="${4}"
_cycle_id="${5}"
_temp_dir=$(mktemp -d)

_md_dir=$(dirname "${_traj_file}")
_md_dirname=$(basename "${_md_dir}")
_md_id=$(echo "${_md_dirname}" | sed 's/md_0*//')
if [[ -z "${_md_id}" ]]; then
  _md_id=1
fi

_cpptraj_in_file="${_temp_dir}/cv.in"
cat <<EOF >"${_cpptraj_in_file}"
parm ${_top_file}
trajin ${_traj_file}
unwrap :1-475
center :1-475@CA mass origin
autoimage
distance S56_A275 :56@CA :275@CA
distance M151_F370 :151@CA :370@CA
run
writedata cv.dat S56_A275 M151_F370
quit
EOF

(
  cd "${_temp_dir}" || exit 1
  cpptraj -i cv.in >cpptraj.log 2>&1
)

if [[ -f "${_temp_dir}/cv.dat" ]]; then
  awk -v m="${_cycle_id}" -v i="${_md_id}" 'NR>1 {printf "%5f  %5f  %d  %d  %d\n", $2, $3, m, i, ($1 - 1)}' "${_temp_dir}/cv.dat" >"${_out_file}"
else
  echo "[ERROR] cv.dat was not generated by cpptraj." >&2
  cat "${_temp_dir}/cpptraj.log" >&2
  rm -rf "${_temp_dir}"
  exit 1
fi

rm -rf "${_temp_dir}"
